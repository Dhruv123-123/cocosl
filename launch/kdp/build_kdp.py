"""KDP paperback of the 2027 Budget Planner: interior PDF and full-wrap cover PDF, sized for Amazon KDP.

    python launch/kdp/build_kdp.py [--year 2027] [--out launch/kdp/dist]

Interior: 8.5 x 11 in trim, no bleed, black ink on white paper. The pages already keep 0.55 in or more from every edge
(KDP's minimum for 24-150 pages is 0.375 in inside and 0.25 in outside). Cover: back + spine + front with 0.125 in
bleed, spine = pages x 0.002252 in (white paper). Under 80 pages, KDP prints no spine text, so the spine stays plain.
Nothing is uploaded. See KDP_NOTES.md for the listing details and the AI disclosure answers.
"""
from __future__ import annotations

import argparse
import html
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "launch" / "etsy"))

import build_etsy  # noqa: E402
import planner_2027 as P  # noqa: E402
from printables import FOOT, page  # noqa: E402

TRIM_W, TRIM_H, BLEED = 8.5, 11.0, 0.125
SPINE_PER_PAGE = 0.002252          # white paper, black ink (KDP)
BOOK_FOOT = "Money Made Simple &middot; {year} Budget Planner"
PERSONAL = "&copy; Money Made Simple &middot; for personal use only, please don't resell or share the file"


def copyright_page(year: int) -> str:
    return (f'''<div class="fill">
      <div style="margin-top:auto;font-size:8.5pt;color:var(--muted);line-height:1.55;max-width:5.2in">
        <p><strong>{year} Budget Planner</strong><br>Money Made Simple</p>
        <p>Copyright &copy; 2026 Money Made Simple. All rights reserved. No part of this book may be reproduced or
        shared without permission, except for brief quotes in reviews.</p>
        <p>This planner is an organising tool for personal use. It is not financial, tax, legal or investment advice.
        Holidays shown are US federal holidays. Starred dates are the usual US tax deadlines; the IRS can change them,
        so check irs.gov.</p>
        <p>Calendars were generated by software and checked date by date. Page layouts and text were created with the
        help of AI tools and reviewed by the publisher.</p>
        <p>Independently published.</p>
      </div></div><div class="foot"><span>{FOOT}</span><span>moneymadesimple</span></div>''')


def interior_pages(year: int) -> list[str]:
    pages = P.build(year, "sun")
    pages[1] = P.how_to_use(year, book=True)
    pages.insert(1, copyright_page(year))
    while len(pages) % 4:                       # even page count, ending on a full sheet
        pages.append(page("<em>Notes</em>", "", '<div class="lines"></div>'))
    foot = BOOK_FOOT.format(year=year)
    out = [p.replace(FOOT, foot).replace(PERSONAL, foot) for p in pages]
    assert not any("resell" in p or "Etsy" in p or "Print at 100%" in p for p in out)
    return out


def interior_html(year: int) -> str:
    css = (build_etsy.HERE / "printables.css").read_text()
    body = "".join(f'<section class="page">{p}</section>\n' for p in interior_pages(year))
    return (f'<!doctype html><html lang="en"><head><meta charset="utf-8"><title>{year} Budget Planner</title>'
            f'<style>@page{{size:{TRIM_W}in {TRIM_H}in;margin:0}}\n{css}</style></head><body>{body}</body></html>')


def spine_width(pages: int) -> float:
    return round(pages * SPINE_PER_PAGE, 4)


def cover_size(pages: int) -> tuple[float, float]:
    return round(2 * BLEED + 2 * TRIM_W + spine_width(pages), 4), TRIM_H + 2 * BLEED


def cover_html(year: int, pages: int) -> str:
    W, H = cover_size(pages)
    sp = spine_width(pages)
    dots = "".join(f'<circle cx="{40 + (i % 6) * 52}" cy="{40 + (i // 6) * 52}" r="{18 if i % 5 else 22}" '
                   f'fill="{"#2fbf71" if i in (3, 8, 13, 14, 20) else "none"}" stroke="#0b1d13" stroke-width="2.5"/>'
                   for i in range(24))
    back_list = "".join(f"<li>{html.escape(x)}</li>" for x in [
        f"Every month of {year}: a dated calendar, a budget page and a spending log",
        "US holidays and the usual tax dates already marked",
        "Year at a glance, money goals, yearly bills and renewals",
        "26-paycheck tracker, savings goals and a debt payoff page",
        f"Monthly reviews, a year in review and a look ahead to {year + 1}"])
    # Text stays 0.375 in inside the trim (0.125 bleed + 0.25 safety). KDP prints its barcode (2 x 1.2 in, white box)
    # at the bottom right of the back; nothing important sits there.
    return f'''<!doctype html><html><head><meta charset="utf-8"><style>
@page{{size:{W}in {H}in;margin:0}}
*{{box-sizing:border-box}} html,body{{margin:0;padding:0}}
body{{width:{W}in;height:{H}in;position:relative;overflow:hidden;background:#f4f1e8;color:#0b1d13;
  font-family:"Inter",system-ui,Arial,sans-serif;-webkit-print-color-adjust:exact;print-color-adjust:exact}}
.panel{{position:absolute;top:0;height:{H}in}}
.back{{left:0;width:{BLEED + TRIM_W}in;padding:{BLEED + 0.6}in 0.75in 0 {BLEED + 0.7}in}}
.spine{{left:{BLEED + TRIM_W}in;width:{sp}in}}
.front{{left:{BLEED + TRIM_W + sp}in;width:{TRIM_W + BLEED}in;padding:{BLEED + 0.8}in {BLEED + 0.7}in 0 0.8in}}
.kick{{text-transform:uppercase;letter-spacing:.16em;font-size:12pt;font-weight:800;color:#1e8a50}}
.yr{{font-size:150pt;font-weight:900;letter-spacing:-.05em;line-height:.85;margin-top:.25in}}
.ttl{{font-size:48pt;font-weight:900;letter-spacing:-.02em;line-height:1;margin-top:.1in}}
.ttl em{{font-style:normal;color:#1e8a50}}
.sub{{font-size:15pt;color:#4b5a51;margin-top:.2in;max-width:6in;line-height:1.35}}
.band{{position:absolute;left:0;right:0;bottom:0;height:{BLEED + 1.1}in;background:#0b1d13}}
.barcode-note{{display:none}}
.brand{{z-index:2;position:absolute;left:0.8in;bottom:{BLEED + 0.42}in;color:#fff;font-weight:800;letter-spacing:.14em;font-size:12pt}}
.back h2{{font-size:26pt;font-weight:900;letter-spacing:-.02em;margin:0 0 .15in;line-height:1.1}}
.back p{{font-size:12pt;line-height:1.5;color:#26352c;max-width:6.4in}}
.back ul{{font-size:12pt;line-height:1.6;padding-left:.25in;max-width:6.4in}}
.back .fine{{font-size:9pt;color:#5b6a61;max-width:4.6in;margin-top:.25in}}
</style></head><body>
<div class="band"></div>
<div class="panel back">
  <div class="kick">Money Made Simple</div>
  <h2>Plan {year} one month at a time.</h2>
  <p>A calm, practical budget planner for a whole year. Plan each month before it starts, write what you spend as you go,
  and check in for ten minutes a week. Every page is already dated, so you can start today.</p>
  <ul>{back_list}</ul>
  <p class="fine">An organising tool, not financial advice. 8.5 x 11 in, {pages} pages, Sunday-start calendars.</p>
</div>
<div class="panel spine"></div>
<div class="panel front">
  <div class="kick">Money Made Simple</div>
  <div class="yr">{year}</div>
  <div class="ttl">Budget <em>Planner</em></div>
  <div class="sub">Monthly budget, bill and spending tracker. January to December {year}.</div>
  <svg viewBox="0 0 330 230" style="width:4in;margin-top:.55in">{dots}</svg>
  <div class="brand">MONEY MADE SIMPLE</div>
</div>
</body></html>'''


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--year", type=int, default=P.YEAR)
    ap.add_argument("--out", default=str(HERE / "dist"))
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    n = len(interior_pages(a.year))
    W, H = cover_size(n)
    work = Path(tempfile.mkdtemp(prefix="kdp-"))
    (work / "interior.html").write_text(interior_html(a.year))
    (work / "cover.html").write_text(cover_html(a.year, n))
    stem = f"{a.year}-Budget-Planner"
    jobs = [{"src": str(work / "interior.html"), "pdf": str(out / f"{stem}-KDP-Interior.pdf")},
            {"src": str(work / "cover.html"), "pdf": str(out / f"{stem}-KDP-Cover.pdf"), "w": round(W * 96), "h": round(H * 96)},
            {"src": str(work / "cover.html"), "png": str(out / f"{stem}-KDP-Cover-preview.png"),
             "w": round(W * 96), "h": round(H * 96)}]
    failures = [f"{Path(r['out']).name}: overflow {r['overflow']}" for r in build_etsy.run_jobs(jobs) if r["overflow"]]
    for f in failures:
        print("FAIL", f)
    print(f"interior: {n} pages, 8.5 x 11 in, no bleed. cover: {W} x {H} in (spine {spine_width(n)} in). -> {out}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
