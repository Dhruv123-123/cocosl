def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--year", type=int, default=P.YEAR)
    ap.add_argument("--out", default=str(HERE / "dist"))
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="kdp-"))
    jobs, report = [], []
    for key, b in books(a.year).items():
        if a.only and key not in a.only:
            continue
        n = len(book_pages(key, a.year))
        W, H = cover_size(n)
        (work / f"{key}-interior.html").write_text(interior_html(key, a.year))
        (work / f"{key}-cover.html").write_text(cover_html(key, n, a.year))
        stem = b["stem"]
        cw, chh = round(W * 96), round(H * 96)
        jobs += [{"src": str(work / f"{key}-interior.html"), "pdf": str(out / f"{stem}-KDP-Interior.pdf")},
                 {"src": str(work / f"{key}-cover.html"), "pdf": str(out / f"{stem}-KDP-Cover.pdf"), "w": cw, "h": chh},
                 {"src": str(work / f"{key}-cover.html"), "png": str(out / f"{stem}-KDP-Cover-preview.png"), "w": cw, "h": chh}]
        report.append(f"{b['title']}: {n} pages, cover {W} x {H} in (spine {spine_width(n)} in)")
    failures = [f"{Path(r['out']).name}: overflow {r['overflow']}" for r in build_etsy.run_jobs(jobs) if r["overflow"]]
    for f in failures:
        print("FAIL", f)
    print("\n".join(report), f"\n-> {out}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
