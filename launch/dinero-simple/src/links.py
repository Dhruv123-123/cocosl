"""UTM-tagged links for Dinero Simple's channel content, following docs/UTM.md (PR #8):
utm_source = platform, utm_medium = bio | social | email, utm_campaign = profile | the content id.

Store links point at the product pages on the Spanish site (which carry Plausible and the buy
button), never straight at an affiliate. Affiliate links never get UTM.

    python launch/dinero-simple/src/links.py     # rewrites launch/dinero-simple/LINKS.md
"""
from __future__ import annotations

from pathlib import Path
from urllib.parse import urlencode

SITE = "https://dinerosimple.netlify.app"
PLATFORMS = ["instagram", "tiktok", "youtube", "facebook", "threads", "x", "pinterest"]

# key -> (name on the description line, site path)
PAGES = {
    "gratis": ("Guía gratis: Tu dinero en orden en 7 días", "/free/"),
    "recortar": ("El Kit para Recortar Gastos ($5)", "/products/el-kit-para-recortar-gastos/"),
    "presupuesto": ("El Presupuesto de 20 Minutos ($12)", "/products/el-presupuesto-de-20-minutos/"),
    "fecha": ("Tu Fecha Sin Deudas ($17)", "/products/tu-fecha-sin-deudas/"),
    "invertir": ("Empieza a Invertir con $100 al Mes ($19)", "/products/empieza-a-invertir-con-100-al-mes/"),
    "paquete": ("El Paquete Dinero Simple, los 4 kits ($29)", "/products/el-paquete-dinero-simple/"),
}


def utm(path: str, source: str, medium: str, campaign: str) -> str:
    return SITE + path + "?" + urlencode({"utm_source": source, "utm_medium": medium, "utm_campaign": campaign})


def bio_link(platform: str) -> str:
    return utm("/links/", platform, "bio", "profile")


def youtube_block(campaign: str, keys: list[str]) -> str:
    """The links block that goes at the end of a long video's YouTube description."""
    lines = [f"{PAGES[k][0]}: {utm(PAGES[k][1], 'youtube', 'social', campaign)}" for k in keys]
    own = any(k != "gratis" for k in keys)
    head = "Enlaces (los productos de pago son nuestros):" if own else "Enlaces:"
    return "\n\n" + head + "\n" + "\n".join(lines)


def add_youtube_links(description: str, campaign: str, keys: list[str]) -> str:
    if not keys or "utm_campaign=" in description:
        return description
    return description.rstrip() + youtube_block(campaign, keys)


def links_md() -> str:
    rows = "\n".join(f"| {p} | {bio_link(p)} |" for p in PLATFORMS)
    store = "\n".join(f"| {name} | {utm(path, 'linkpage', 'bio', key)} |" for key, (name, path) in PAGES.items()
                      if key != "gratis")
    return f"""# Dinero Simple: tagged links

Generated by `src/links.py`, following the UTM rules in `docs/UTM.md` (PR #8). Plausible picks up the
`utm_*` values when someone lands on the site, so you can see which platform and which video sent each
visit and sale. Change the domain in `src/links.py` (`SITE`) if the site moves, then rerun it.

## Profile links (paste one into each profile)

| Platform | Bio link |
|---|---|
{rows}

## Store links for link pages and pinned comments

When you link a product from a Linktree-style page or a pinned comment instead of the site's own `/links/` page:

| Product | Link |
|---|---|
{store}

## In posts

- TikTok and Instagram captions say "enlace en la bio", so the bio link above does the tagging.
- Long YouTube videos end their description with direct product links tagged
  `utm_source=youtube&utm_medium=social&utm_campaign=<content id>` (added by the build scripts).
- The welcome emails tag every link to the site with `utm_source=newsletter&utm_medium=email&utm_campaign=welcome-d<day>`
  (site.json `utm_emails`).
- Never add UTM to affiliate links or to source links (FTC, IRS, CFPB...).
"""


if __name__ == "__main__":
    out = Path(__file__).resolve().parents[1] / "LINKS.md"
    out.write_text(links_md())
    print(f"Wrote {out}")
