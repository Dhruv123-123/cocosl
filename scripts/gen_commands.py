ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "COMMANDS.md"


def commands() -> dict[str, str]:
    sys.path.insert(0, str(ROOT / "src"))
    from contentfactory.cli import build_parser
    p = build_parser()
    sp = next(a for a in p._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help or "" for c in sp._choices_actions}
    return {name: helps.get(name, "") for name in sp.choices}


def render() -> str:
    cmds = commands()
    seen: set[str] = set()
    out = ["# Every `factory` command", "",
           "Generated by `python scripts/gen_commands.py` from the CLI itself; `factory <command> --help` has the options.",
           "Nothing here posts or sends on its own: publishing is a dry run until FACTORY_DRY_RUN=0, and emails need --confirm.", ""]
    rest = sorted(n for n in cmds if not any(n in g for _, g in GROUPS))
    for title, names in GROUPS + [("More commands", rest)]:
        rows = [n for n in names if n in cmds and n not in seen]
        if not rows:
            continue
        out += [f"## {title}", "", "| Command | What it does |", "|---|---|"]
        for n in rows:
            seen.add(n)
            out.append(f"| `factory {n}` | {cmds[n].replace('|', '/')} |")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text() != text:
            print("docs/COMMANDS.md is out of date: run python scripts/gen_commands.py")
            sys.exit(1)
        print("docs/COMMANDS.md is up to date")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT} ({len(commands())} commands)")
