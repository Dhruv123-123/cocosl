"""Write docs/COMMANDS.md: every `factory` command, grouped, with its one-line help.

    python scripts/gen_commands.py          # rewrite the file
    python scripts/gen_commands.py --check  # exit 1 if it's out of date (the tests run this)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

GROUPS = [
    ("Your routine", ["today", "triage", "time", "weekly-review", "launch-mode", "keyword-check", "ui", "serve"]),
    ("Make content", ["ideas", "idea", "produce", "daily", "import", "repurpose", "challenge", "voice", "recordings",
                      "batch-record", "broll", "motion", "numbers", "rerender", "renderq", "brandkit", "pack", "channels"]),
    ("Review", ["review", "review-gate", "approve", "reject", "audit-originality", "launch-check", "preflight"]),
    ("Schedule and post", ["schedule", "unschedule", "reslot", "calendar", "publish", "manual", "export-week",
                           "youtube-plan"]),
    ("Measure", ["metrics", "stats", "scorecard", "insights", "report", "funnel"]),
    ("Email and site", ["sequences", "sequence-check", "sequence-preview", "sequence-export", "subscribers-export",
                        "digest", "digest-send", "newsletter", "linkpage", "salespage", "site", "comments"]),
    ("Money", ["revenue", "expense", "links", "product", "payment-link"]),
    ("Ad studio and B2B", ["clients", "pitch", "proposal", "order", "invoice", "ad", "portfolio", "whitelabel"]),
    ("Brands", ["brands", "brand", "niche", "new-brand"]),
    ("Setup and upkeep", ["init", "status", "doctor", "auth", "backup", "restore", "cleanup", "demo"]),
]
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "COMMANDS.md"


def commands() -> dict[str, str]:
    sys.path.insert(0, str(ROOT / "src"))
    from contentfactory.cli import build_parser
    p = build_parser()
    sp = next(a for a in p._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help or "" for c in sp._choices_actions}
    return {name: helps.get(name, "") for name in sp.choices}


def render() -> str:
    cmds = commands()
    seen: set[str] = set()
    out = ["# Every `factory` command", "",
           "Generated by `python scripts/gen_commands.py` from the CLI itself; `factory <command> --help` has the options.",
           "Nothing here posts or sends on its own: publishing is a dry run until FACTORY_DRY_RUN=0, and emails need --confirm.", ""]
    for title, names in GROUPS + [("Other", [n for n in cmds if not any(n in g for _, g in GROUPS)])]:
        rows = [n for n in names if n in cmds and n not in seen]
        if not rows:
            continue
        out += [f"## {title}", "", "| Command | What it does |", "|---|---|"]
        for n in rows:
            seen.add(n)
            out.append(f"| `factory {n}` | {cmds[n].replace('|', '/')} |")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text() != text:
            print("docs/COMMANDS.md is out of date: run python scripts/gen_commands.py")
            sys.exit(1)
        print("docs/COMMANDS.md is up to date")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT} ({len(commands())} commands)")
